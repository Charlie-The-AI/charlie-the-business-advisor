'use client';

import { useState } from 'react';
import { Recommendation } from '../lib/types';
import {
  AlertCircle,
  ArrowRight,
  CheckCircle2,
  Clock,
  Sparkles,
  XCircle,
  Database,
} from 'lucide-react';

interface RecommendationCardProps {
  recommendation: Recommendation;
  onStatusChange?: (id: string, newStatus: Recommendation['status']) => void;
}

export function RecommendationCard({
  recommendation,
  onStatusChange,
}: RecommendationCardProps) {
  const [status, setStatus] = useState(recommendation.status);

  const handleUpdate = (newStatus: Recommendation['status']) => {
    setStatus(newStatus);
    if (onStatusChange) {
      onStatusChange(recommendation.id, newStatus);
    }
  };

  const categoryLabels = {
    revenue_concentration: 'Revenue Concentration',
    customer_retention: 'Customer Retention',
    sales_growth: 'Sales Performance',
    product_profitability: 'Product Profitability',
    cash_flow: 'Cash Flow Management',
  };

  const priorityColors = {
    critical: 'bg-rose-500/10 text-rose-400 border-rose-500/30',
    high: 'bg-amber-500/10 text-amber-400 border-amber-500/30',
    medium: 'bg-blue-500/10 text-blue-400 border-blue-500/30',
    low: 'bg-gray-500/10 text-gray-400 border-gray-500/30',
  };

  return (
    <div className="p-6 rounded-xl bg-[#111827] border border-[#1f2937] hover:border-gray-700 transition flex flex-col justify-between">
      <div>
        {/* Badges & Header */}
        <div className="flex items-center justify-between gap-3 mb-3">
          <div className="flex items-center gap-2">
            <span className="text-xs font-semibold px-2.5 py-0.5 rounded-full bg-blue-500/10 text-blue-400 border border-blue-500/20">
              {categoryLabels[recommendation.category] ?? recommendation.category}
            </span>
            <span
              className={`text-[11px] font-bold px-2 py-0.5 rounded uppercase tracking-wider border ${
                priorityColors[recommendation.priority]
              }`}
            >
              {recommendation.priority} Priority
            </span>
          </div>

          {/* Status Pill */}
          <span
            className={`text-xs font-medium px-2.5 py-0.5 rounded-full capitalize ${
              status === 'accepted'
                ? 'bg-emerald-500/15 text-emerald-400 border border-emerald-500/30'
                : status === 'dismissed'
                ? 'bg-gray-800 text-gray-400 border border-gray-700'
                : status === 'reviewing'
                ? 'bg-indigo-500/15 text-indigo-400 border border-indigo-500/30'
                : 'bg-amber-500/15 text-amber-400 border border-amber-500/30'
            }`}
          >
            {status}
          </span>
        </div>

        {/* Title & Explanation */}
        <h4 className="text-base font-semibold text-white mb-2 leading-snug">
          {recommendation.title}
        </h4>
        <p className="text-xs text-gray-300 leading-relaxed mb-4">
          {recommendation.explanation}
        </p>

        {/* Supporting Evidence Metrics */}
        {recommendation.evidence && recommendation.evidence.length > 0 && (
          <div className="mb-4 p-3 rounded-lg bg-[#0d131f] border border-gray-800">
            <span className="text-[10px] uppercase font-bold tracking-wider text-gray-400 flex items-center gap-1.5 mb-2">
              <Database className="w-3 h-3 text-blue-400" />
              <span>Verified Numerical Evidence</span>
            </span>
            <div className="grid grid-cols-2 sm:grid-cols-3 gap-2">
              {recommendation.evidence.map((ev, i) => (
                <div key={i} className="p-2 rounded bg-gray-900/60 border border-gray-800">
                  <span className="block text-[10px] text-gray-400 truncate">{ev.metricName}</span>
                  <span className="text-xs font-bold text-gray-100">{ev.formattedValue}</span>
                </div>
              ))}
            </div>
          </div>
        )}

        {/* Recommended Strategic Action */}
        <div className="p-3.5 rounded-lg bg-blue-950/20 border border-blue-500/30 mb-5">
          <span className="text-[10px] uppercase font-bold tracking-wider text-blue-400 flex items-center gap-1.5 mb-1.5">
            <Sparkles className="w-3 h-3 text-blue-400" />
            <span>Recommended Strategic Action</span>
          </span>
          <p className="text-xs text-blue-200 font-medium leading-relaxed">
            {recommendation.recommended_action}
          </p>
        </div>
      </div>

      {/* Action Decision Buttons */}
      <div className="flex items-center justify-between pt-3 border-t border-gray-800/80 gap-2">
        <div className="text-[11px] text-gray-400 flex items-center gap-1">
          <Clock className="w-3 h-3 text-gray-400" />
          <span>Generated by Charlie</span>
        </div>

        <div className="flex items-center gap-2">
          {status !== 'dismissed' && (
            <button
              onClick={() => handleUpdate('dismissed')}
              className="text-xs px-2.5 py-1 rounded-md text-gray-400 hover:text-gray-200 hover:bg-gray-800 transition"
            >
              Dismiss
            </button>
          )}

          {status !== 'reviewing' && (
            <button
              onClick={() => handleUpdate('reviewing')}
              className="text-xs px-2.5 py-1 rounded-md text-indigo-400 hover:bg-indigo-950/40 border border-indigo-500/30 transition"
            >
              Mark In Review
            </button>
          )}

          {status !== 'accepted' && (
            <button
              onClick={() => handleUpdate('accepted')}
              className="text-xs px-3 py-1 rounded-md bg-blue-600 hover:bg-blue-500 text-white font-medium flex items-center gap-1 transition shadow-sm"
            >
              <CheckCircle2 className="w-3 h-3" />
              <span>Accept Action</span>
            </button>
          )}
        </div>
      </div>
    </div>
  );
}
